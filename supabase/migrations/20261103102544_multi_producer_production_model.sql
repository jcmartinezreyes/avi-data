create or replace function private.user_can_access_organization(p_organization_id uuid, p_write boolean default false)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.organization_memberships m
    where m.organization_id = p_organization_id
      and m.user_id = (select auth.uid())
      and (not p_write or m.role in ('owner', 'admin', 'operator'))
  );
$$;

create or replace function private.user_can_access_farm(p_farm_id bigint, p_write boolean default false)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.granjas f
    where f.id = p_farm_id
      and private.user_can_access_organization(f.organization_id, p_write)
  );
$$;

create or replace function private.user_can_access_lote(p_lote_id bigint, p_write boolean default false)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.lotes l
    join public.galpones g on g.id = l.galpon_id
    where l.id = p_lote_id
      and private.user_can_access_farm(g.granja_id, p_write)
  );
$$;

create or replace function private.user_can_access_daily(p_daily_id bigint, p_write boolean default false)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.registros_diarios d
    where d.id = p_daily_id
      and private.user_can_access_lote(d.lote_id, p_write)
