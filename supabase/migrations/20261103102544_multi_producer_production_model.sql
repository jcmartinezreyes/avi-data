create or replace function public.create_organization(p_name text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_organization_id uuid;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;
  if length(trim(coalesce(p_name, ''))) = 0 then
    raise exception 'Organization name is required';
  end if;
  if exists (select 1 from public.organization_memberships m where m.user_id = v_user_id) then
    raise exception 'This user already belongs to an organization';
  end if;

  insert into public.organizations(name, created_by)
  values (trim(p_name), v_user_id)
  returning id into v_organization_id;

  insert into public.organization_memberships(organization_id, user_id, role)
  values (v_organization_id, v_user_id, 'owner');

  return v_organization_id;
end;
$$;
revoke all on function public.create_organization(text) from public, anon;
grant execute on function public.create_organization(text) to authenticated;

create or replace function private.validate_box_daily_link()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_lote_id bigint;
begin
  select d.lote_id into v_lote_id
  from public.registros_diarios d
  where d.id = new.registro_diario_id;

  if v_lote_id is null then
    raise exception 'Daily record not found';
  end if;
  if new.box_id is not null and not exists (
    select 1 from public.galpon_boxes b
    where b.id = new.box_id and b.lote_id = v_lote_id
  ) then
    raise exception 'Box must belong to the lot of the daily record';
  end if;
  return new;
end;
$$;

revoke all on function private.validate_box_daily_link() from public;

create trigger registros_diarios_box_validate_link
before insert or update of registro_diario_id, box_id on public.registros_diarios_box
for each row execute function private.validate_box_daily_link();

create trigger mediciones_produccion_validate_link
before insert or update of registro_diario_id, box_id on public.mediciones_produccion
for each row execute function private.validate_box_daily_link();

